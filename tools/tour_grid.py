"""Emit a rectangular grid of scene references as an authored .tour scene.

The grid scene carries the project's PRIMARY (.geometry) root reference
first (the recipe resolver's packer input) and then one non-root
`reference` line per cell, each with its own placeholder transform.
A referenced `.tour` scene is inlined per occurrence by
ApplySceneReferences, so the cell cost is a FULL copy of that scene
(nodes + pool rows), not a lightweight GPU instance.

  python tools/tour_grid.py \
      --source content/scenes/Sponza.tour \
      --root-source content/models/Sponza/Sponza.geometry \
      --columns 4 --rows 4 --spacing-x 40 --spacing-z 40 \
      --output ../Sponza/content/scenes/SponzaGrid.tour

Sizing note: the renderer's GPU-filter candidate table is 262,144
slots (GFX_MAX_BATCH_SLOTS). A Sponza copy is ~12,946 meshlet clusters,
so only ~20 copies actually cull/draw in one frame regardless of how
many the scene authoring tool emits.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def parser():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--source", required=True,
                   help="project-relative .tour scene (or .geometry) to "
                        "reference once per cell")
    p.add_argument("--root-source", default=None,
                   help="project-relative .geometry for the scene's -root "
                        "reference (the packer's primary input); omit only "
                        "when --source is already that geometry")
    p.add_argument("--columns", type=int, default=1000,
                   help="cells along +X (default 1000)")
    p.add_argument("--rows", type=int, default=1000,
                   help="cells along +Z (default 1000)")
    p.add_argument("--spacing-x", type=float, default=40.0,
                   help="X distance between cell origins, metres (default 40)")
    p.add_argument("--spacing-z", type=float, default=40.0,
                   help="Z distance between cell origins, metres (default 40)")
    p.add_argument("--origin-y", type=float, default=0.0,
                   help="cell origin Y, metres (default 0)")
    p.add_argument("--name-prefix", default="Cell",
                   help="placeholder name prefix (default Cell)")
    p.add_argument("--output", required=True, type=Path,
                   help="destination .tour path")
    p.add_argument("--dry-run", action="store_true",
                   help="print the plan without writing the scene")
    return p


def main(argv=None):
    args = parser().parse_args(argv)
    if args.columns <= 0 or args.rows <= 0:
        print("tour_grid: --columns/--rows must be positive", file=sys.stderr)
        return 2
    if not args.source.lower().endswith((".tour", ".geometry", ".gltf", ".glb")):
        print("tour_grid: --source must be a .tour scene or model artifact",
              file=sys.stderr)
        return 2
    root_source = args.root_source
    if not root_source:
        if not args.source.lower().endswith(".geometry"):
            print("tour_grid: --root-source is required when --source is not "
                  "a .geometry (the recipe resolver takes references[0] as "
                  "the packer's primary input)", file=sys.stderr)
            return 2
        root_source = args.source

    cells = args.columns * args.rows
    origin_x = -(args.columns - 1) * 0.5 * args.spacing_x
    origin_z = -(args.rows - 1) * 0.5 * args.spacing_z

    if args.dry_run:
        print(f"tour_grid: {args.columns} x {args.rows} = {cells} cells")
        print(f"  root   : {root_source}")
        print(f"  source : {args.source}")
        print(f"  extent : {args.columns * args.spacing_x:.1f} x "
              f"{args.rows * args.spacing_z:.1f} m")
        print(f"  output : {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    tmp = args.output.with_suffix(args.output.suffix + ".tmp")
    written = 0
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"//Name: {args.output.name}\n")
        f.write("//Generated by tools/tour_grid.py\n")
        f.write(f"reference -root -n 0 -source \"{root_source}\" "
                f"-name \"{args.name_prefix}Root\";\n")
        f.write("fileInfo -k \"application\" -v \"tourmaline-tour\";\n")
        f.write("fileInfo -k \"product\" -v \"Tourmaline\";\n")
        f.write("fileInfo -k \"version\" -v \"1\";\n")
        for row in range(args.rows):
            z = origin_z + row * args.spacing_z
            for col in range(args.columns):
                x = origin_x + col * args.spacing_x
                f.write(f"reference -n 0 -source \"{args.source}\" "
                        f"-name \"{args.name_prefix}_{row:04d}_{col:04d}\" "
                        f"-t {x:g} {args.origin_y:g} {z:g};\n")
                written += 1
    tmp.replace(args.output)
    print(f"tour_grid: wrote {written} references "
          f"({args.columns} x {args.rows}) to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
