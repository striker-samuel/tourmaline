#pragma once
// THE APP MANIFEST (appmanifest 2, file extension .tapp): THE RELEASE
// POINTER — the atomic selection of one complete generation of
// content. A recipe build publishes it after every pak passes
// verification; the runtime reads it, joins the listed paks into ONE
// content session (through their OWN "#ids" identity tables — the
// manifest carries NO catalog: the paks speak for themselves), and
// loads the entry scene BY IDENTITY.
//
// Format (line-oriented; # comments; CRLF/LF; quoted strings — the
// recipe parser's grammar conventions):
//
//   # Tourmaline Runtime Project
//   appmanifest 2
//   entry <pak-file> <scene-name>
//
//   [paks]
//   shared.pak
//   world.pak
//   props.pak
//
//  * `entry` names the pak FILE carrying the entry scene + the COOKED
//    scene's NAME inside that pak (ListPakScenes' name — the identity
//    the build recorded; tour-built paks name it "scene").
//  * [paks] is the GENERATION'S COMPLETE SET in mount order (the plan's
//    topological order). The entry pak must be listed.
//  * Every pak path is RELATIVE TO THE MANIFEST'S OWN DIRECTORY (a
//    moved build directory keeps working — never a developer-machine
//    absolute path). Load rejects absolute and '..'-escaping paths.
//
// Version 2 dropped the v1 [ids] table + the `catalog` line (the
// per-pak identity tables replaced them: the records + the identity
// fingerprint live in the PAKS, the runtime's ContentRegistry reads
// them from there — a v1 manifest fails loud, content recooks).
//
// Generated by the build executor (project_pipeline), consumed by the
// runtime host (app). Written LAST: the executor stages the paks,
// reopens + polices every one, and only then publishes the manifest —
// a failed build leaves the previous manifest + its paks intact.

#include <cstdint>
#include <string>
#include <vector>

namespace smvk {

inline constexpr uint32_t kAppManifestVersion = 2;

// THE RELEASE POINTER'S payload: WHICH paks constitute the active
// generation + WHICH scene is the entry. NOTHING ELSE — the content
// identities (ids, kinds, paths, the id->scene joins) live in the PAKS'
// OWN "#ids" tables (see pak.h's kPakAssetIdsPath); the runtime's
// ContentRegistry reads them from there.
struct AppManifest {
	uint32_t version = 0;
	std::string entryPak;   // pak file (manifest-relative)
	std::string entryScene; // the cooked scene's name inside entryPak
	std::vector<std::string> paks; // the generation's complete set,
	                               // mount order, manifest-relative
};

// The catalog identity KIND BYTES — an ABI shared by three writers:
// the generated project.h's AssetKind enum values, the per-pak
// identity tables' kind bytes, and the runtime's validation.
// Do not renumber - new kinds APPEND.
inline constexpr uint8_t kCatalogKindScene = 0;
inline constexpr uint8_t kCatalogKindTexture = 1;
inline constexpr uint8_t kCatalogKindMesh = 2;
inline constexpr uint8_t kCatalogKindSound = 3;
// PROJECT-AUTHORED SHADER assets (compiled .spv the project owns —
// distinct from the ENGINE-NATIVE set the engine-shaders.pak carries;
// project recipes never control mandatory engine shader inclusion).
inline constexpr uint8_t kCatalogKindShader = 4;
// GI bake SETS (.givolumemanifest — a baked lighting set of one or
// more GI volumes; loaded by GiKey through AssetManager::LoadGI,
// blendable across two resident sets).
inline constexpr uint8_t kCatalogKindGi = 5;
// The kind string <-> byte mapping ("scene"/"texture"/"mesh"/"sound"/
// "shader"/"gi"; false for any other spelling).
[[nodiscard]] bool CatalogKindFromString(const std::string& kind,
	uint8_t& out);
[[nodiscard]] const char* CatalogKindToString(uint8_t kind);

// The CATALOG FINGERPRINT fold: FNV-1a64 over the rows in EMISSION
// order (bucket order: scenes, textures, meshes, sounds, shaders,
// gi; id-sorted within — the generator's exact emission sequence),
// folding each row's STABLE IDENTITY: id (8 LE bytes), kind byte,
// path bytes + a 0 separator. IDENTITY ONLY — the owning pak, its
// mount index and the package filenames are DELIBERATELY NOT folded
// (the physical/addressing halves are selection state, not identity:
// repacking an asset into a different package, reordering the mounts
// or a content-addressed rename leaves the fingerprint PROOF intact
// — the compiled game and its content only need to agree on WHAT
// the assets are, never on which package carries them). Raw pointer
// + count per the public-API convention.
[[nodiscard]] uint64_t ComputeCatalogFingerprint(
	const uint64_t* ids, const uint8_t* kinds,
	const char* const* paths, size_t count);

// Text round-trip. Save refuses an invalid manifest (no entry, entry
// pak not listed, empty paks, absolute/escaping paths). Load applies
// the same validation — a corrupt or hand-mangled manifest fails the
// launch visibly, never a guess.
bool SaveAppManifest(const std::string& path, const AppManifest& m,
	std::string& err);
bool LoadAppManifest(const std::string& path, AppManifest& out,
	std::string& err);
bool LoadAppManifestText(const std::string& text, AppManifest& out,
	std::string& err);

// Structural validation shared by both directions (also the cheap
// "is this manifest complete" probe).
bool ValidateAppManifest(const AppManifest& m, std::string& err);

} // namespace smvk
