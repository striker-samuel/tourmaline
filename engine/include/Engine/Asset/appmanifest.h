#pragma once
// THE APP MANIFEST (appmanifest 1, file extension .tapp): the GENERATED
// runtime launch manifest a recipe build publishes after every pak
// passes verification. It is deliberately smaller than the recipe — the
// runtime does NO dependency discovery and NO cooking; it reads this
// file, mounts the listed paks IN ORDER, and loads the entry scene BY
// IDENTITY (never the source .tour, never a scene index).
//
// Format (line-oriented; # comments; CRLF/LF; quoted strings — the
// recipe parser's grammar conventions):
//
//   # Tourmaline Runtime Project
//   appmanifest 1
//   entry <pak-file> <scene-name>
//
//   [paks]
//   shared.pak
//   world.pak
//   props.pak
//
//  * `entry` names the pak FILE carrying the entry scene + the COOKED
//    scene's NAME inside that pak (ListPakScenes' name — the identity
//    the build recorded; tour-built paks name it "scene").
//  * [paks] is the MOUNT ORDER (the plan's topological order). The
//    entry pak must be listed.
//  * Every pak path is RELATIVE TO THE MANIFEST'S OWN DIRECTORY (a
//    moved build directory keeps working — never a developer-machine
//    absolute path). Load rejects absolute and '..'-escaping paths.
//
// Generated by the build executor (project_pipeline), consumed by the
// runtime host (app). Written LAST: the executor stages the paks,
// reopens + polices every one, and only then publishes the manifest —
// a failed build leaves the previous manifest + its paks intact.

#include <cstdint>
#include <string>
#include <vector>

namespace smvk {

inline constexpr uint32_t kAppManifestVersion = 1;

// One CONTENT-ID row (the generated project.h's catalog, mirrored into
// the manifest so the RUNTIME resolves stable ids without the header —
// the spec's "the cooker uses those exact identifiers in the cooked
// metadata"). kind: "scene" | "texture" | "mesh" | "sound"; pak is the
// FILE (manifest-relative, listed in [paks]); path is the
// project-relative content path (VFS-addressable for textures/sounds;
// the scene's tour path for scenes). Scene rows carry one more field —
// `name`, the COOKED scene's name inside the pak (what ListPakScenes
// reports; the build records it the same way it records the entry
// scene's name). The name is the id->scene JOIN the runtime's
// numeric-addressed scene loading needs: a scene id resolves to
// (pak, name), never to "whatever scene sits at index 0". Empty = the
// row predates the name (or the owning pak was not rebuilt here): the
// runtime then infers the target from a SINGLE-scene pak and refuses
// multi-scene paks loudly (recook).
struct AppManifestAsset {
	uint64_t id = 0;
	std::string kind;
	std::string pak;
	std::string path;
	// Scene rows only: the cooked scene's name (see above). Written as
	// an optional 5th token on the [ids] line; non-scene rows leave it
	// empty and validation rejects a name on them.
	std::string name;
};

struct AppManifest {
	uint32_t version = 0;
	std::string entryPak;   // pak file (manifest-relative)
	std::string entryScene; // the cooked scene's name inside entryPak
	std::vector<std::string> paks; // ordered (mount order), relative
	// The content-id table (OPTIONAL — manifests from before the
	// catalog mirror carry none; the runtime façade degrades to
	// path-only). Ids are unique; each row's pak must be listed.
	std::vector<AppManifestAsset> assets;
	// The CATALOG FINGERPRINT (the deployment manifest's half of the
	// compiled-catalog contract): FNV-1a64 over the [ids] rows' STABLE
	// identity in emission order (see ComputeCatalogFingerprint). The
	// generated project.h emits the same fold as
	// project::CatalogFingerprint — the runtime compares them so a
	// compiled game and its deployed content can never silently
	// disagree. 0 = the line is absent (a pre-fingerprint manifest —
	// validation degrades to the row-by-row form).
	uint64_t catalogFingerprint = 0;

	// The row for a stable id (nullptr = unknown). The runtime façade's
	// core lookup.
	[[nodiscard]] const AppManifestAsset* FindAsset(uint64_t id) const;
};

// The catalog identity KIND BYTES — an ABI shared by three writers:
// the generated project.h's AssetKind enum values, the manifest's
// kind strings (mapped at the fold), and the runtime's validation.
// Do not renumber.
inline constexpr uint8_t kCatalogKindScene = 0;
inline constexpr uint8_t kCatalogKindTexture = 1;
inline constexpr uint8_t kCatalogKindMesh = 2;
inline constexpr uint8_t kCatalogKindSound = 3;
// The kind string <-> byte mapping ("scene"/"texture"/"mesh"/"sound";
// false for any other spelling).
[[nodiscard]] bool CatalogKindFromString(const std::string& kind,
	uint8_t& out);
[[nodiscard]] const char* CatalogKindToString(uint8_t kind);

// The CATALOG FINGERPRINT fold: FNV-1a64 over the rows in EMISSION
// order (bucket order: scenes, textures, meshes, sounds; id-sorted
// within — the generator's exact emission sequence), folding each
// row's stable identity: id (8 LE bytes), kind byte, pakIndex (4 LE
// bytes), path bytes + a 0 separator. The published pak FILENAME is
// deliberately NOT folded — content-addressed names change every
// cook; the fingerprint proves IDENTITY, not cook state. Raw pointer
// + count per the public-API convention.
[[nodiscard]] uint64_t ComputeCatalogFingerprint(
	const uint64_t* ids, const uint8_t* kinds,
	const uint32_t* pakIndices, const char* const* paths, size_t count);

// Text round-trip. Save refuses an invalid manifest (no entry, entry
// pak not listed, empty paks, absolute/escaping paths). Load applies
// the same validation — a corrupt or hand-mangled manifest fails the
// launch visibly, never a guess.
bool SaveAppManifest(const std::string& path, const AppManifest& m,
	std::string& err);
bool LoadAppManifest(const std::string& path, AppManifest& out,
	std::string& err);
bool LoadAppManifestText(const std::string& text, AppManifest& out,
	std::string& err);

// Structural validation shared by both directions (also the cheap
// "is this manifest complete" probe).
bool ValidateAppManifest(const AppManifest& m, std::string& err);

} // namespace smvk
